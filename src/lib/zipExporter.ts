import JSZip from 'jszip';
import { EXTENSION_FILES } from './extensionFiles';

export async function generateExtensionZip(): Promise<Blob> {
  const zip = new JSZip();

  // Add root files
  for (const file of EXTENSION_FILES) {
    if (file.path === 'cleaner.js') {
      // Fetch fresh cleaner.js from server or fallback to code
      try {
        const res = await fetch('/extension/cleaner.js');
        if (res.ok) {
          const text = await res.text();
          zip.file('cleaner.js', text);
          continue;
        }
      } catch {
        // Fallback below
      }
    }
    zip.file(file.path, file.content);
  }

  // Add icons folder with SVG and generated PNGs
  const iconsFolder = zip.folder('icons');
  if (iconsFolder) {
    // Try to fetch real PNG icons generated by script
    try {
      const [res16, res48, res128, resSvg] = await Promise.all([
        fetch('/extension/icons/icon16.png').then(r => r.ok ? r.arrayBuffer() : null),
        fetch('/extension/icons/icon48.png').then(r => r.ok ? r.arrayBuffer() : null),
        fetch('/extension/icons/icon128.png').then(r => r.ok ? r.arrayBuffer() : null),
        fetch('/extension/icons/icon.svg').then(r => r.ok ? r.text() : null)
      ]);

      if (res16) iconsFolder.file('icon16.png', res16);
      if (res48) iconsFolder.file('icon48.png', res48);
      if (res128) iconsFolder.file('icon128.png', res128);
      if (resSvg) iconsFolder.file('icon.svg', resSvg);
    } catch {
      // If network fetch fails, ensure files are present
    }
  }

  return await zip.generateAsync({ type: 'blob' });
}

export function triggerDownload(blob: Blob, filename: string = 'CleanLink-Extension-v1.0.0.zip') {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
